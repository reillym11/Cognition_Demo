"""Generate the mock IdP persona login page from infra/oidc/personas.json."""

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TENANT = "11111111-2222-4333-8444-555555555555"


def claims_for(p: dict) -> dict:
    c = {
        "oid": p["oid"],
        "tid": TENANT,
        "name": p["name"],
        "preferred_username": f"{p['username']}@contoso-fintech.test",
        "region": p["region"],
    }
    if p.get("overage"):
        c["_claim_names"] = {"groups": "src1"}
        c["_claim_sources"] = {
            "src1": {"endpoint": f"https://graph.microsoft.com/v1.0/users/{p['oid']}/getMemberObjects"}
        }
    elif p.get("roles"):
        c["roles"] = p["roles"]
    return c


def main() -> None:
    personas = json.loads((ROOT / "infra/oidc/personas.json").read_text())["personas"]
    forms = []
    for p in personas:
        claims = html.escape(json.dumps(claims_for(p)), quote=True)
        hidden = " hidden" if p.get("hidden") else ""
        forms.append(
            f'<form method="post" data-persona="{html.escape(p["username"])}"{hidden}>'
            f'<input type="hidden" name="username" value="{html.escape(p["oid"])}">'
            f'<input type="hidden" name="claims" value="{claims}">'
            f'<button type="submit">{html.escape(p["name"])}</button></form>'
        )
    # The app's sign-in screen passes the chosen role as login_hint; this page then completes on its own.
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Sign in</title>
<style>body{{font-family:"Segoe UI",system-ui,sans-serif;max-width:420px;margin:6rem auto;padding:0 1rem;color:#242424}}
h1{{font-size:1.25rem;font-weight:600}}p{{color:#616161}}form{{margin:.25rem 0}}
button{{width:100%;text-align:left;padding:.5rem .75rem;border:1px solid #d1d1d1;border-radius:4px;background:#fff;cursor:pointer}}
button:hover,button:focus{{border-color:#0f6cbd}}.auto #pick{{display:none}}#busy{{display:none}}.auto #busy{{display:block}}</style></head>
<body><p id="busy">Signing in...</p><div id="pick"><h1>Sign in</h1><p>Demo sign-in. Synthetic data only.</p>
{"".join(forms)}</div>
<script>
const hint = new URLSearchParams(location.search).get("login_hint");
const form = hint && document.querySelector(`form[data-persona="${{CSS.escape(hint)}}"]`);
if (form) {{ document.body.classList.add("auto"); form.submit(); }}
</script></body></html>
"""
    (ROOT / "infra/oidc/login.html").write_text(page)
    visible = [
        {"username": p["username"], "name": p["name"], "group": p["group"], "description": p["persona"], "roles": p.get("roles") or []}
        for p in personas
        if not p.get("hidden")
    ]
    (ROOT / "web/src/shell/personas.gen.ts").write_text(
        "// Generated by scripts/gen_login_page.py from infra/oidc/personas.json. Do not edit.\n"
        "export const PERSONAS: { username: string; name: string; group: string; description: string; roles: string[] }[] = "
        + json.dumps(visible, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    main()
